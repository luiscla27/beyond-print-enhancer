const printStylesContent = fs.readFileSync(printStylesPath, 'utf8');




describe('Spell Persistence in JSON', function() {
  let window, Storage;

    before(async function() {
        const dom = new JSDOM(`<!DOCTYPE html><html><body></body></html>`, {
          url: "http://localhost",
          runScripts: "dangerously"
        });
        window = dom.window;

    const { indexedDB, IDBKeyRange } = require('fake-indexeddb');
    window.indexedDB = indexedDB;
    window.IDBKeyRange = IDBKeyRange;
    global.indexedDB = indexedDB;
    global.IDBKeyRange = IDBKeyRange;
    window.__DDB_TEST_MODE__ = true;
    window.eval(elementWrapperContent);
    window.eval(domManagerContent);
    window.eval(contextMenuContent);
    window.eval(assetCatalogContent);
    window.eval(storageContent);
window.eval(imageProcessorContent);
window.eval(printStylesContent);
window.eval(sectionUtilsContent);
    window.eval(modalsContent);
    window.eval(propertiesPanelContent);
    window.eval(layoutScanContent);
    window.eval(layoutApplyContent);
    window.eval(persistenceContent);
    window.eval(controlsContent);
    window.eval(shapePickerContent);
    window.eval(spellsUiContent);
    window.eval(filtersContent);
    window.eval(layoutOpsContent);
    window.eval(sectionCloningContent);
    window.eval(mainJsContent);
    Storage = window.Storage;
    await Storage.init();
  });

  it('should include spell_cache in scanLayout', async function() {
    const spellData = {
      name: 'Magic Missile',
      level: 1,
      description: 'You create three glowing darts of magical force.',
      range: '120 feet',
      school: 'Evocation'
    };

    await Storage.saveSpells([spellData]);
    
    const layout = await window.scanLayout();
    assert.ok(layout.spell_cache, 'layout should have spell_cache');
    const found = layout.spell_cache.find(s => s.name === 'Magic Missile');
    assert.deepStrictEqual(found, spellData);
  });

  it('should restore spell_cache in applyLayout', async function() {
    const spellData = {
      name: 'Shield',
      level: 1,
      description: 'An invisible barrier of magical force appears...',
      range: 'Self',
      school: 'Abjuration'
    };

    const layout = {
      version: '1.1.0',
      sections: {},
      spell_cache: [spellData]
    };

    // Clear current cache
    const db = await Storage.init();
    const transaction = db.transaction(['spell_cache'], 'readwrite');
    transaction.objectStore('spell_cache').clear();
    await new Promise(resolve => transaction.oncomplete = resolve);

    await window.applyLayout(layout);
    
    const cachedSpell = await Storage.getSpell('Shield');
    assert.deepStrictEqual(cachedSpell, spellData);
  });
});
