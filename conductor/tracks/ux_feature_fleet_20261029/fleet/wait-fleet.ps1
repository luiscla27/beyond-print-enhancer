<#
.SYNOPSIS
  Waits until fewer than MaxCount reasonix fleet instances matching a pattern are running.

.DESCRIPTION
  Generated by the fleet-delegation skill (templates/wait-fleet.ps1). Polls
  node.exe processes whose CommandLine contains the given literal pattern
  (e.g. "LAUNCH-PROMPT.md" for launch.bat). With -MaxCount N it returns once the
  live count drops BELOW N (rolling-pool top-up). Exits 0 on success, 1 on timeout.
  With -CountOnly it just prints the live count. READ-ONLY: never touches the runtime.

.PARAMETER Pattern
  Literal substring to match against node.exe command lines.

.PARAMETER PollSeconds
  Seconds between polls (default 30).

.PARAMETER TimeoutMinutes
  Abort after this many minutes while the condition is unmet (0 = wait forever).

.PARAMETER MaxCount
  Return once fewer than this many instances are running (default 1 = wait until zero).

.PARAMETER CountOnly
  Print the live count and exit immediately (no waiting).
#>
[CmdletBinding()]
param(
    [string]$Pattern = "LAUNCH-PROMPT.md",
    [int]$PollSeconds = 30,
    [int]$TimeoutMinutes = 720,
    [int]$MaxCount = 1,
    [switch]$CountOnly
)

$start = Get-Date
while ($true) {
    $n = @(Get-CimInstance Win32_Process -Filter "Name='node.exe'" |
        Where-Object { $_.CommandLine -like "*$Pattern*" }).Count
    if ($CountOnly) {
        Write-Output $n
        exit 0
    }
    Write-Host ("[wait-fleet] {0} instance(s) running (pattern: {1}; waiting until < {2})" -f $n, $Pattern, $MaxCount)
    if ($n -lt $MaxCount) {
        Write-Host "[wait-fleet] target reached."
        exit 0
    }
    $elapsed = ((Get-Date) - $start).TotalMinutes
    if ($TimeoutMinutes -gt 0 -and $elapsed -ge $TimeoutMinutes) {
        Write-Host ("[wait-fleet] TIMEOUT after {0} minutes." -f $elapsed)
        exit 1
    }
    Start-Sleep -Seconds $PollSeconds
}
