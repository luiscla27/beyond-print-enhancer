<#
.SYNOPSIS
  Drain/rolling-pool waiter WITH per-track stuck recovery (age + progress-stall watchdog).

.DESCRIPTION
  Generated by the fleet-delegation skill (templates/wait-recover.ps1). Like the plain
  waiter (returns once fewer than MaxCount instances are running), but on every poll it
  detects STUCK tracks and self-heals - the #1 loss mode in real fleets was instances that
  computed for hours and died with all progress unrecorded:
  - AGE rule: a live track whose processes have run longer than TrackTimeoutMinutes without
    completing is STUCK.
  - PROGRESS-STALL rule: a live track that has produced NO new progress line within
    ProgressStallMinutes is STUCK (it may be idling in a verify loop with the work done but
    unrecorded).
  Stuck tracks are KILLED and RELAUNCHED from their per-track LAUNCH-PROMPT.md (which is
  resume-safe: it re-reads progress + reconcile output first). Relaunches per track are
  capped by MaxRecoveries (persisted in <runtime>/recover_counts.json); progress-stall state
  is persisted in <runtime>/stall_state.json so the window survives across wait calls.
  Exits 0 when the count target is reached, 1 on global timeout.

  This watchdog is the ONLY authorized killer in the fleet: it belongs to the launcher and
  reclaims nothing else. Other agents/scripts MUST never kill fleet processes.

.PARAMETER Pattern
  Per-FLEET process pattern (default: <this script's dir>\tracks\track-). The watchdog
  only ever sees/kills processes of THIS fleet — fleets in other projects are invisible
  to it (user-mandated per-project scoping 2026-08-15).

.PARAMETER PollSeconds
  Seconds between polls (default 30).

.PARAMETER TimeoutMinutes
  Global wait timeout (default 4320 = 72 h).

.PARAMETER TrackTimeoutMinutes
  A track running longer than this without completing is STUCK (default 700).

.PARAMETER ProgressStallMinutes
  SILENCE window (default 700, deliberately NOT tightened). A live track whose append-only
  `runtime/heartbeat-log/<track>.jsonl` has not advanced for this long is STUCK. The signal is
  read through `stall-signal.py silence`; when that log is absent the track is reported
  UNINSTRUMENTED and the withdrawn progress-COUNT clock (progress lines are written only after
  a unit is VERIFIED, so zero lines is normal for a long first unit) is used only as a
  non-regressive fallback. Derive the value from real samples with
  `python stall-signal.py derive --fleet-dir .` — it refuses a sample of fewer than 3 unit
  durations / 5 heartbeat gaps, because a threshold from less is an anecdote.

.PARAMETER MaxCount
  Return once fewer than this many instances are running (default 1).

.PARAMETER MaxRecoveries
  Max relaunches per track before giving up on it (default 3).

.PARAMETER RecoverOnce
  Do a single recovery pass + count, then exit (no polling loop).

.PARAMETER TrackRoot
  Per-track manifests dir (default: <script dir>\tracks).

.PARAMETER Runtime
  Fleet runtime dir (default: <script dir>\runtime).

.PARAMETER LogDir
  Where relaunched-instance logs land (default: <script dir>\logs).

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File wait-recover.ps1 -MaxCount 4
#>
[CmdletBinding()]
param(
    [string]$Pattern = "",
    [int]$PollSeconds = 30,
    [int]$TimeoutMinutes = 4320,
    [int]$TrackTimeoutMinutes = 700,
    [int]$ProgressStallMinutes = 700,
    [int]$MaxCount = 1,
    [int]$MaxRecoveries = 3,
    [int]$MaxSteps = 800,
    [switch]$RecoverOnce,
    [string]$TrackRoot = "",
    [string]$Runtime = "",
    [string]$LogDir = ""
)

$here = $PSScriptRoot
if (-not $TrackRoot) { $TrackRoot = Join-Path $here "tracks" }
if (-not $Runtime)   { $Runtime   = Join-Path $here "runtime" }
if (-not $LogDir)    { $LogDir    = Join-Path $here "logs" }
# PER-PROJECT SCOPING (user-mandated 2026-08-15): default pattern = THIS fleet's tracks
# path, so the watchdog only sees/kills this fleet — other projects' fleets are invisible.
if (-not $Pattern)   { $Pattern   = Join-Path $here "tracks\track-" }
# logs must be a DIRECTORY: a stray 0-byte file named "logs" would pass Test-Path
# and break every relaunch redirection ("The system cannot find the path specified.").
# NOTE: Test-Path "logs\." does NOT work here — PS normalizes the trailing \. away and
# returns True for a FILE too. Use -PathType Container (verified on this machine).
if (Test-Path $LogDir) {
    if (-not (Test-Path $LogDir -PathType Container)) {
        Remove-Item -Force $LogDir
    }
}
if (-not (Test-Path $LogDir)) { New-Item -ItemType Directory -Path $LogDir -Force | Out-Null }

$countFile = Join-Path $Runtime "recover_counts.json"
$stallFile = Join-Path $Runtime "stall_state.json"

function ConvertTo-Hashtable($obj) {
    # PowerShell 5.1 has NO `ConvertFrom-Json -AsHashtable` (that landed in PS 6). Using
    # it here did not fail loudly: it threw INSIDE the try/catch below, so
    # `recover_counts.json` / `stall_state.json` were silently reset on EVERY invocation -
    # MaxRecoveries never accumulated ("effectively unbounded relaunch", a reviewer finding
    # on 2026-09-17) and the progress-stall window never opened.
    #
    # It MUST be defined before the call sites below: a PowerShell function only exists from
    # the point its definition statement EXECUTES, so a helper declared after the `if` blocks
    # that use it is not a fix at all - the call throws, the surrounding catch resets the file,
    # and the symptom is byte-identical to the bug.
    $ht = @{}
    if ($null -eq $obj) { return $ht }
    foreach ($p in $obj.PSObject.Properties) { $ht[$p.Name] = $p.Value }
    return $ht
}

$counts = @{}
if (Test-Path $countFile) { try { $counts = ConvertTo-Hashtable (Get-Content -Raw $countFile | ConvertFrom-Json) } catch { $counts = @{} } }
$stall  = @{}
if (Test-Path $stallFile)  { try { $stall  = ConvertTo-Hashtable (Get-Content -Raw $stallFile  | ConvertFrom-Json) } catch { $stall = @{} } }

function Save-Json([string]$path, $obj) {
    try { $obj | ConvertTo-Json | Set-Content -Path $path -Encoding UTF8 } catch { }
}

function Recover-Track([string]$tid, [int[]]$pids, [string]$reason, [double]$prog, [double]$total) {
    $n = if ($counts.ContainsKey($tid)) { [int]$counts[$tid] } else { 0 }
    if ($n -ge $MaxRecoveries) {
        Write-Host ("[recover] {0} STUCK ({1}, {2}/{3}) - EXHAUSTED after {4} recoveries, leaving it" -f $tid, $reason, $prog, $total, $n) -ForegroundColor Red
        return
    }
    Write-Host ("[recover] {0} STUCK ({1}, {2}/{3}) - killing and relaunching (recovery {4})" -f $tid, $reason, $prog, $total, ($n + 1)) -ForegroundColor Yellow
    foreach ($procId in $pids) { & taskkill /PID $procId /T /F 2>&1 | Out-Null }
    Start-Sleep -Seconds 2
    $prompt = Join-Path $TrackRoot "$tid\LAUNCH-PROMPT.md"
    if (Test-Path $prompt) {
        $task = "Execute the file $prompt as your complete task. Read it fully and follow every instruction exactly, including the heartbeat, lock, deferral, and resume rules it references."
        $log = Join-Path $LogDir "recover-$tid.log"
        # Relaunch with the SAME per-track session layout as launch.bat: unique --dir
        # OUTSIDE the repo (workspace-write wedge fix, verified 2026-08-15), both
        # add-dirs, the fleet-wide worker model, and --permission-mode yolo (the
        # `ask` default auto-declines every write/bash in minimized windows).
        # MODEL FALLBACK (user mandate 2026-08-16): a track whose worker recorded a
        # Muse failure marker (runtime\status\<tid>\model_fallback.json) relaunches
        # on the fallback tier instead of the primary (sticky per track).
        $fleetDir = 'C:\luiscla27\projects\dndbeyond-printenhance\conductor\tracks\ux_feature_fleet_20261029\fleet'
        $repoRoot = 'C:\luiscla27\projects\dndbeyond-printenhance'
        $primaryModel = 'anthropic-api-meta-ai/muse-spark-1.2-contributor'
        $fallbackModel = 'deepseek-flash/deepseek-v4-flash'
        $fbMarker = Join-Path $Runtime "status\$tid\model_fallback.json"
        $workerModel = $(if ((Test-Path $fbMarker) -and $fallbackModel) { $fallbackModel } else { $primaryModel })
        $wsRoot = Join-Path $env:USERPROFILE ("reasonix-fleet-workspaces\" + (Split-Path -Leaf (Split-Path -Parent $PSScriptRoot)))
        $sessionDir = Join-Path $wsRoot $tid
        if (-not (Test-Path $sessionDir)) { New-Item -ItemType Directory -Path $sessionDir | Out-Null }
        $modelArg = $(if ($workerModel) { "--model $workerModel" } else { "" })
        $cmd = "C:\luiscla27\projects\dndbeyond-printenhance\reasonix.exe run --dir `"$sessionDir`" --add-dir `"$fleetDir`" --add-dir `"$repoRoot`" $modelArg --permission-mode yolo --max-steps $MaxSteps `"$task`" 1>$log 2>&1"
        Start-Process -FilePath "cmd.exe" -ArgumentList '/c', $cmd -WindowStyle Minimized | Out-Null
        Write-Host ("[recover] {0} relaunched on model {1} ({2})" -f $tid, $workerModel, $log)
    } else {
        Write-Host ("[recover] {0} no launch prompt at {1} - skipped relaunch" -f $tid, $prompt) -ForegroundColor Red
    }
    $counts[$tid] = $n + 1
    Save-Json $countFile $counts
}

$start = Get-Date
while ($true) {
    $procs = @(Get-CimInstance Win32_Process -Filter "Name='node.exe' OR Name='reasonix.exe'" |
        Where-Object { $_.CommandLine -like "*$Pattern*" })

    $tracks = @{}
    foreach ($p in $procs) {
        if ($p.CommandLine -match 'track-(\d+)') {
            $tid = "track-$($matches[1])"
            if (-not $tracks.ContainsKey($tid)) { $tracks[$tid] = @() }
            $tracks[$tid] += [int]$p.ProcessId
        }
    }

    # ---- recovery pass (age rule + progress-stall watchdog) ----
    $now = Get-Date
    $liveTracks = @($tracks.Keys)
    foreach ($tid in $liveTracks) {
        $oldest = $now
        foreach ($procId in $tracks[$tid]) {
            $pr = Get-Process -Id $procId -ErrorAction SilentlyContinue
            if ($pr -and $pr.StartTime -lt $oldest) { $oldest = $pr.StartTime }
        }
        $ageMin = [math]::Round(($now - $oldest).TotalMinutes, 1)

        $total = 0
        $mf = Join-Path $TrackRoot "$tid\manifest.json"
        if (Test-Path $mf) { try { $total = [int]((Get-Content -Raw -Encoding UTF8 $mf | ConvertFrom-Json).code_count) } catch {} }
        $prog = 0
        $pf = Join-Path $Runtime "progress\$tid.jsonl"
        if (Test-Path $pf) { $prog = @(Get-Content $pf | Where-Object { $_.Trim() }).Count }
        if ($total -gt 0 -and $prog -ge $total) {
            Write-Host ("[recover] {0} running {1} min but COMPLETE {2}/{3} - not stuck" -f $tid, $ageMin, $prog, $total)
            $stall.Remove($tid)
            continue
        }

        $stuck = $false; $reason = ""
        # ---- SILENCE clock (2026-09-17): true liveness = the append-only heartbeat log ----
        # The count clock below (the progress LINE count) was withdrawn as a stall signal:
        # `track-prompt.md` appends a progress line only AFTER a unit is VERIFIED, so for a
        # track's first long unit ZERO lines is the state of a HEALTHY worker. It could not
        # separate "long unit" from "stalled" at any threshold, and all three candidate
        # values (700 -> 90 -> 45) were falsified — see
        # `modelstack_framework/temp/archived/ISSUE_fleet_launcher_halt_and_stall_signal_20260917.md` §3.
        #
        # The probe is ALWAYS called with an explicit `--silent-after`, and its exit code is
        # read: the unthresholded report is `ALIVE` BY CONSTRUCTION (that script's default is
        # 0 = "never classify, just report the seconds"), so reading that token as a liveness
        # verdict is the false-liveness defect the cop handoff measured — a track with ZERO
        # processes was reported `ALIVE 366`. A non-zero exit means UNINSTRUMENTED (no
        # heartbeat log for that track), which is NEVER treated as healthy.
        $silenceSec = -1
        $silentVerdict = $false
        $probe = Join-Path $here "stall-signal.py"
        if (Test-Path $probe) {
            $silentAfterSecs = [int]($ProgressStallMinutes * 60)
            $v = & python $probe silence --fleet-dir $here --track $tid --silent-after $silentAfterSecs 2>$null
            $probeRc = $LASTEXITCODE
            if ($probeRc -eq 0 -and "$v" -match '^(ALIVE|SILENT)\s+(\d+)') {
                $silenceSec = [double]$matches[2]
                $silentVerdict = ($matches[1] -eq 'SILENT')
            }
        }
        if ($silenceSec -ge 0) {
            if ($silentVerdict) {
                $stuck = $true
                $reason = "silent $([math]::Round($silenceSec / 60, 1)) min (heartbeat), $prog/$total units done"
            }
            $stall[$tid] = @{ silence_sec = [int]$silenceSec; count = $prog; seen = $now.ToString("o") }
        } else {
            # UNINSTRUMENTED - say so out loud, then fall back to the withdrawn count clock so
            # behaviour cannot regress. Never silently report an uninstrumented track healthy.
            Write-Host ("[stall] {0} UNINSTRUMENTED (no runtime/heartbeat-log/{0}.jsonl) - falling back to the progress-count clock" -f $tid) -ForegroundColor DarkYellow
            if ($stall.ContainsKey($tid)) {
                $prevCount = [int]$stall[$tid].count
                $prevSeen  = [datetime]$stall[$tid].seen
                if ($prog -gt $prevCount) {
                    $stall[$tid] = @{ count = $prog; seen = $now.ToString("o") }
                } elseif (($now - $prevSeen).TotalMinutes -ge $ProgressStallMinutes) {
                    $stuck = $true
                    $reason = "no new progress in $ProgressStallMinutes min ($prog/$total) [uninstrumented]"
                }
            } else {
                $stall[$tid] = @{ count = $prog; seen = $now.ToString("o") }
            }
        }

        if (-not $stuck -and $ageMin -ge $TrackTimeoutMinutes) {
            $stuck = $true
            $reason = "running $ageMin min with $prog/$total"
        }

        if ($stuck) {
            Recover-Track $tid $tracks[$tid] $reason $prog $total
            $stall[$tid] = @{ count = $prog; seen = $now.ToString("o") }
        }
    }
    foreach ($tid in @($stall.Keys)) {
        if ($tid -notin $liveTracks) { $stall.Remove($tid) }
    }
    Save-Json $stallFile $stall

    # ---- resume pass: paused-exited tracks (no live process, unit incomplete) ----
    # The live recovery pass above can never see a worker that EXITED (max-steps pause,
    # crash, taskkill) - no process means no STUCK detection. If such a track has EVER
    # started (heartbeat or lock on record) and its unit is not done, resume it from its
    # resume-safe LAUNCH-PROMPT so a pause can never strand a unit. Bounded by MaxRecoveries.
    foreach ($tdir in @(Get-ChildItem -Path $TrackRoot -Directory -Filter "track-*" -ErrorAction SilentlyContinue)) {
        $tid = $tdir.Name
        if ($tracks.ContainsKey($tid)) { continue }
        $total = 0
        $mf = Join-Path $tdir.FullName "manifest.json"
        if (Test-Path $mf) { try { $total = [int]((Get-Content -Raw -Encoding UTF8 $mf | ConvertFrom-Json).code_count) } catch {} }
        if ($total -le 0) { continue }
        $prog = 0
        $pf = Join-Path $Runtime "progress\$tid.jsonl"
        if (Test-Path $pf) { $prog = @(Get-Content $pf | Where-Object { $_.Trim() }).Count }
        if ($prog -ge $total) { continue }
        $everStarted = Test-Path (Join-Path $Runtime "heartbeats\$tid.json")
        if (-not $everStarted) {
            foreach ($lf in @(Get-ChildItem (Join-Path $Runtime "locks\*.lock") -ErrorAction SilentlyContinue)) {
                $lk = Get-Content -Raw $lf.FullName -ErrorAction SilentlyContinue
                if ($lk -match ('"owner_track"\s*:\s*"' + [regex]::Escape($tid) + '"')) { $everStarted = $true; break }
            }
        }
        if (-not $everStarted) { continue }
        Recover-Track $tid @() ("paused-exited, not live ($prog/$total done)") $prog $total
    }
    $n = @($procs | Where-Object { $_.Name -eq 'node.exe' }).Count
    Write-Host ("[wait-recover] {0} instance(s) running (waiting until < {1})" -f $n, $MaxCount)

    if ($RecoverOnce) { exit 0 }
    if ($n -lt $MaxCount) {
        Write-Host "[wait-recover] target reached."
        exit 0
    }
    if ($TimeoutMinutes -gt 0 -and ($now - $start).TotalMinutes -ge $TimeoutMinutes) {
        Write-Host ("[wait-recover] TIMEOUT after {0} min, {1} instance(s) running." -f $TimeoutMinutes, $n) -ForegroundColor Red
        exit 1
    }
    Start-Sleep -Seconds $PollSeconds
}
